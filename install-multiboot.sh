#!/usr/bin/env bash
# install-multiboot.sh - turn a USB disk into an ISOlator multiboot disk.
#
# Result:
#   <dev>1  512 MB  FAT32  MBOOT-EFI   GRUB (Debian packages), UEFI boot only
#   <dev>2  rest    exFAT  MULTIBOOT   ISOs and files, readable on Windows and Linux
#
# The ISO menu lives in MULTIBOOT:/multiboot/menu.cfg (written by gen-menu.py);
# the EFI partition's grub.cfg only loads it.
#
# Usage: sudo ./install-multiboot.sh <device> <expected serial>
#   e.g. sudo ./install-multiboot.sh /dev/sdX "$(lsblk -dno SERIAL /dev/sdX)"
# The serial is required so that a renumbered device (sda <-> sdb) can never
# make the script wipe the wrong disk.
set -euo pipefail

LABEL_EFI=MBOOT-EFI
LABEL_DATA=MULTIBOOT

die() { echo "ERROR: $*" >&2; exit 1; }

[ $# -eq 2 ] || die "usage: sudo $0 <device> <expected serial>"
DEV=$1
EXPECTED_SERIAL=$2

[ "$(id -u)" -eq 0 ] || die "run it with sudo"
[ -n "${SUDO_UID:-}" ] || die "run it through sudo (not as root directly) so that the files belong to you"
[ -n "${SUDO_GID:-}" ] || die "SUDO_GID is not set"

# --- Guard rails: is this really the intended disk? ---------------------------
[ -b "$DEV" ] || die "$DEV does not exist (is the disk plugged in?)"
SERIAL=$(lsblk -dno SERIAL "$DEV" | tr -d ' ')
TRAN=$(lsblk -dno TRAN "$DEV" | tr -d ' ')
[ "$SERIAL" = "$EXPECTED_SERIAL" ] || die "$DEV has serial '$SERIAL', expected '$EXPECTED_SERIAL'. Stopping."
[ "$TRAN" = "usb" ] || die "$DEV is not a USB disk ($TRAN). Stopping."
lsblk -nso NAME "$(findmnt -no SOURCE /)" | grep -qw "$(basename "$DEV")" && die "$DEV holds the running system! Stopping."

echo
lsblk -o NAME,SIZE,FSTYPE,LABEL,MODEL,SERIAL,TRAN "$DEV"
echo
echo "EVERYTHING on $DEV ($SERIAL, $TRAN) is about to be erased."
read -rp "Type YES in capitals to continue: " answer
[ "$answer" = "YES" ] || die "cancelled"

# --- Unmount ------------------------------------------------------------------
for p in $(lsblk -lno NAME "$DEV" | tail -n +2); do
    umount "/dev/$p" 2>/dev/null || true
done

# Partition device names: /dev/sda -> /dev/sda1, /dev/nvme0n1 -> /dev/nvme0n1p1.
case "$DEV" in
    *[0-9]) PART="${DEV}p" ;;
    *)      PART="$DEV" ;;
esac

# --- GPT partitioning ---------------------------------------------------------
echo ">> Wiping signatures and partitioning"
for p in $(lsblk -lno NAME "$DEV" | tail -n +2); do wipefs -a "/dev/$p"; done
wipefs -a "$DEV"
parted -s "$DEV" \
    mklabel gpt \
    mkpart "$LABEL_EFI" fat32 1MiB 513MiB \
    set 1 esp on \
    mkpart "$LABEL_DATA" 513MiB 100% \
    set 2 msftdata on
partprobe "$DEV"; udevadm settle; sleep 2

echo ">> Formatting"
mkfs.vfat -F 32 -n "$LABEL_EFI" "${PART}1"
mkfs.exfat -L "$LABEL_DATA" "${PART}2"
udevadm settle

# --- GRUB on the EFI partition ------------------------------------------------
TMP=$(mktemp -d)
ESP="$TMP/efi"; DATA="$TMP/data"
mkdir -p "$ESP" "$DATA"
cleanup() { umount "$ESP" "$DATA" 2>/dev/null || true; rmdir "$ESP" "$DATA" "$TMP" 2>/dev/null || true; }
trap cleanup EXIT

mount "${PART}1" "$ESP"
echo ">> Installing GRUB (UEFI x86_64, removable mode, the PC's NVRAM is left untouched)"
grub-install \
    --target=x86_64-efi \
    --efi-directory="$ESP" \
    --boot-directory="$ESP/boot" \
    --removable \
    --no-nvram \
    --no-uefi-secure-boot

cat > "$ESP/boot/grub/grub.cfg" <<EOF
# grub.cfg - EFI partition of the ISOlator disk.
# Only loads the ISO menu from the exFAT partition.
insmod part_gpt
insmod fat
insmod exfat
insmod loopback
insmod iso9660
insmod all_video

set timeout=-1
set isolabel=$LABEL_DATA
search --no-floppy --label --set=isopart \$isolabel
export isopart isolabel

if [ -f (\$isopart)/multiboot/menu.cfg ]; then
    source (\$isopart)/multiboot/menu.cfg
else
    echo "menu.cfg not found on partition \$isolabel: run gen-menu.py"
fi

menuentry "--- Firmware settings (UEFI)" { fwsetup }
menuentry "--- Reboot" { reboot }
menuentry "--- Power off" { halt }
EOF

# --- Layout of the exFAT partition --------------------------------------------
mount -t exfat -o "uid=$SUDO_UID,gid=$SUDO_GID" "${PART}2" "$DATA"
mkdir -p "$DATA"/{x86_64,arm64,files,multiboot}
echo "# Generated by gen-menu.py: copy ISOs to this partition, then run it." > "$DATA/multiboot/menu.cfg"

sync
echo
echo ">> Done. Copy your ISOs, then run ./gen-menu.py."
lsblk -o NAME,SIZE,FSTYPE,LABEL "$DEV"
